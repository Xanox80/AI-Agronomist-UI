/** Parses the JSON object a user typed as a proposal payload; null when it is not a JSON object. */
export function parseProposalPayload(text: string): Record<string, unknown> | null {
  try {
    const value: unknown = JSON.parse(text);
    return value !== null && typeof value === 'object' && !Array.isArray(value)
      ? (value as Record<string, unknown>)
      : null;
  } catch {
    return null;
  }
}
